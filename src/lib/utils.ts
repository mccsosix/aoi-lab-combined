export function toSimplified(text: string): string {
  let result = "";
  for (let i = 0; i < text.length; i++) {
    if (i + 1 < text.length) {
      const two = text.slice(i, i + 2);
      if (cleanMap[two] && cleanMap[two] !== two) {
        result += cleanMap[two];
        i++;
        continue;
      }
    }
    const ch = text[i];
    result += (cleanMap[ch] && cleanMap[ch] !== ch) ? cleanMap[ch] : ch;
  }
  return result;
}
